"""Regenerate CompPhysics/docs/CATALOG.md from the same discovery used by explore.py."""
from pathlib import Path
import sys
import os
sys.dont_write_bytecode = True
from urllib.parse import quote

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from explore import ROOT, PROJECT, catalog


def main():
    lines = ['# Program catalog', '',
             'Browse by topic below, or search with `python3 explore.py list <text>`.', '',
             'Run a program with `python3 explore.py run "topic/file"`. C++ demos build automatically; Python scripts use your current environment. Python modules are supporting code, not standalone programs. See [Getting started](GETTING_STARTED.md) for dependencies.', '',
             'Generated by `python3 CompPhysics/scripts/update_catalog.py`; the launcher discovers the current files automatically.', '']
    entries = catalog()
    groups = sorted({e.category for e in entries}, key=str.lower)
    lines.extend(['## Topics', ''])
    lines.extend(f'- [{g}](#{g.lower().replace("/", "")})' for g in groups)
    for group in groups:
        lines.extend(['', f'## {group}', '', '| Source | Type |', '| --- | --- |'])
        for entry in entries:
            if entry.category == group:
                link = quote(os.path.relpath(entry.path, PROJECT / 'docs'), safe='/')
                lines.append(f'| [{entry.path.name}]({link}) | {entry.kind} |')
    (PROJECT / 'docs' / 'CATALOG.md').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
